#!/usr/bin/env bash
# apt-guard: lock apt/apt-get/dpkg/aptitude by default, unlock on demand.
# Target: Debian 13 (trixie). Run as root: sudo bash install-apt-guard.sh
set -euo pipefail

if [[ $EUID -ne 0 ]]; then
    echo "Run as root (sudo bash $0)" >&2
    exit 1
fi

REAL_DIR=/usr/local/lib/apt-guard/bin
STATE_DIR=/run/apt-guard
STATE_FILE="$STATE_DIR/unlocked"
GUARD_BIN=/usr/local/sbin/apt-guard
TARGETS=(apt apt-get dpkg aptitude)   # aptitude only wrapped if present

mkdir -p "$REAL_DIR"
mkdir -p /etc/apt-guard

# ── 1. Relocate real binaries (idempotent) ──────────────────────────────
for bin in "${TARGETS[@]}"; do
    src="$(command -v "$bin" 2>/dev/null || true)"
    [[ -z "$src" ]] && continue                      # not installed, skip
    dest="$REAL_DIR/$bin"

    # Already relocated on a previous run
    if [[ -e "$dest" ]]; then
        continue
    fi

    # Skip if $src is already our own wrapper (re-run safety)
    if grep -q "apt-guard" "$src" 2>/dev/null; then
        continue
    fi

    mv "$src" "$dest"
    echo "Relocated $src -> $dest"
done

# ── 2. Write wrapper installed at each original path ────────────────────
write_wrapper() {
    local name="$1" path="$2"
    cat > "$path" <<EOF
#!/usr/bin/env bash
# apt-guard wrapper for $name — DO NOT EDIT (regenerated by install-apt-guard.sh)
set -euo pipefail
REAL="$REAL_DIR/$name"
STATE="$STATE_FILE"
USER_INFO="\$(whoami) uid=\$(id -u) tty=\$(tty 2>/dev/null || echo none)"

if [[ -f "\$STATE" ]]; then
    logger -t apt-guard "ALLOWED: $name \$* by \$USER_INFO"
    exec "\$REAL" "\$@"
else
    logger -t apt-guard "BLOCKED: $name \$* by \$USER_INFO"
    echo "apt-guard: package management is locked." >&2
    echo "Run: sudo apt-guard unlock [minutes]   (default 15)" >&2
    exit 126
fi
EOF
    chmod 755 "$path"
    chown root:root "$path"
}

for bin in "${TARGETS[@]}"; do
    [[ -x "$REAL_DIR/$bin" ]] || continue
    # original path is wherever it used to resolve; standard is /usr/bin
    orig_path="/usr/bin/$bin"
    write_wrapper "$bin" "$orig_path"
    echo "Installed wrapper: $orig_path"
done

# ── 3. Control command: apt-guard unlock|lock|status ────────────────────
cat > "$GUARD_BIN" <<'EOF'
#!/usr/bin/env bash
set -euo pipefail
STATE_DIR=/run/apt-guard
STATE_FILE="$STATE_DIR/unlocked"
TIMER_UNIT=apt-guard-relock

usage() { echo "usage: apt-guard {unlock [minutes]|lock|status}" >&2; exit 1; }

[[ $EUID -ne 0 ]] && { echo "apt-guard: must run as root" >&2; exit 1; }
[[ $# -ge 1 ]] || usage

mkdir -p "$STATE_DIR"

case "$1" in
    unlock)
        mins="${2:-15}"
        date -Is > "$STATE_FILE"
        logger -t apt-guard "UNLOCKED by $(logname 2>/dev/null || whoami) for ${mins}m"
        # cancel any pending relock, then schedule a fresh one
        systemctl stop "${TIMER_UNIT}.timer" 2>/dev/null || true
        systemd-run --unit="$TIMER_UNIT" --on-active="${mins}min" \
            /usr/local/sbin/apt-guard lock >/dev/null
        echo "apt-guard: UNLOCKED for ${mins} minute(s). Auto-relock scheduled."
        ;;
    lock)
        rm -f "$STATE_FILE"
        systemctl stop "${TIMER_UNIT}.timer" 2>/dev/null || true
        logger -t apt-guard "LOCKED"
        echo "apt-guard: LOCKED."
        ;;
    status)
        if [[ -f "$STATE_FILE" ]]; then
            echo "apt-guard: UNLOCKED since $(cat "$STATE_FILE")"
        else
            echo "apt-guard: LOCKED"
        fi
        ;;
    *) usage ;;
esac
EOF
chmod 755 "$GUARD_BIN"
chown root:root "$GUARD_BIN"

echo
echo "apt-guard installed. State: LOCKED (default, fail-secure, resets on reboot)."
echo "Usage:"
echo "  sudo apt-guard unlock          # unlock for 15 min"
echo "  sudo apt-guard unlock 60       # unlock for 60 min"
echo "  sudo apt-guard lock            # relock immediately"
echo "  apt-guard status               # check state"
echo
echo "All allow/deny events are logged via 'logger -t apt-guard' -> check with:"
echo "  journalctl -t apt-guard -f"
